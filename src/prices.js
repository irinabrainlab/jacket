export function labelOf(lang, sr) {
  return lang === 'en' ? english[sr] ?? sr : sr
}

export function parseDin(price) {
  return Number(String(price).replace(/\./g, '').replace(',', '.')) || 0
}

export function formatDin(amount) {
  return String(Math.round(amount)).replace(/\B(?=(\d{3})+(?!\d))/g, '.')
}

